    private void btnChangePwdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChangePwdActionPerformed
        String newPassword = new String(txtNewPwd.getPassword()).trim();
        String confirmPassword = new String(txtConfirmPwd.getPassword()).trim();

        // --- Validation ---
        if (newPassword.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a new password!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            txtNewPwd.requestFocus();
            return;
        }
        if (newPassword.length() < 4) {
            JOptionPane.showMessageDialog(this, "Password must be at least 4 characters!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            txtNewPwd.requestFocus();
            return;
        }
        if (newPassword.length() > 50) {
            JOptionPane.showMessageDialog(this, "Password cannot exceed 50 characters!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            txtNewPwd.requestFocus();
            return;
        }
        if (confirmPassword.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please confirm your new password!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            txtConfirmPwd.requestFocus();
            return;
        }
        if (!newPassword.equals(confirmPassword)) {
            JOptionPane.showMessageDialog(this, "Passwords do not match!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            txtConfirmPwd.setText("");
            txtConfirmPwd.requestFocus();
            return;
        }

        // --- DB Update ---
        Connection conn = getConnection();
        if (conn == null) {
            JOptionPane.showMessageDialog(this, "Cannot connect to the database!\nPlease check your MySQL server.", "Database Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String hashedPassword = hashPassword(newPassword);
        String sql = "UPDATE users SET password = ?, first_time = 0 WHERE user_id = ?";
        try (PreparedStatement pst = conn.prepareStatement(sql)) {
            pst.setString(1, hashedPassword);
            pst.setInt(2, currentUserId);
            int rows = pst.executeUpdate();
            if (rows > 0) {
                JOptionPane.showMessageDialog(this,
                    "Password changed successfully!\nYou can now use your new password to log in.",
                    "Success", JOptionPane.INFORMATION_MESSAGE);
                new Dashbord(currentUsername, currentRole).setVisible(true);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to update password. Please try again.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (SQLException ex) {
            logger.log(Level.SEVERE, "Failed to change password", ex);
            JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnChangePwdActionPerformed

    private void btnSkipActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSkipActionPerformed
        int confirm = JOptionPane.showConfirmDialog(this,
            "Are you sure you want to skip?\n\nYou are currently using the default password.\nIt is strongly recommended to change it for security.",
            "Skip Password Change", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);

        if (confirm == JOptionPane.YES_OPTION) {
            // Mark first_time = 0 so user is not prompted every login
            markFirstTimeHandled();
            new Dashbord(currentUsername, currentRole).setVisible(true);
            this.dispose();
        }
    }//GEN-LAST:event_btnSkipActionPerformed

